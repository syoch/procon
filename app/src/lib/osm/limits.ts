/**
 * 1 回の OSM 取得で扱うセル (1/64° 格子) 数の上限。
 * Overpass の 1 クエリに載るデータ量を抑え、広域表示での OOM を防ぐ。
 * 超える場合はキャッシュ済みの分だけで続行する。
 * 実際のセル数は log_lines に記録し、この値を実測で見直す。
 */
export const MAX_OSM_CELLS = 512;

/**
 * Overpass の取得にかける時間の上限 [ms]。
 * クエリの `[timeout:30]` はサーバ側の打ち切りなので、応答が返らない場合に備えて
 * クライアント側でも切る。サーバの `remark` を受け取れるよう 30 秒より少し長くする。
 */
export const OSM_FETCH_BUDGET_MS = 35_000;
