/**
 * 1 回の OSM 取得で扱うセル (1/64° 格子) 数の上限。
 * Overpass の 1 クエリに載るデータ量を抑え、広域表示での OOM を防ぐ。
 * 512 セルは 23×23 格子で、37°N ではおよそ 40km×32km に相当する。
 * 超える場合はキャッシュ済みの分だけで続行する。
 *
 * 仮の値。OOM の主因はセル数ではなく取得要素数なので、
 * `log_lines` の requested / fetch と取得要素数の実測で見直す。
 */
export const MAX_OSM_CELLS = 512;

/**
 * Overpass の取得にかける時間の上限 [ms]。
 * クエリの `[timeout:30]` はサーバ側の打ち切りで、応答しない場合に備えて
 * クライアント側でも切る。header だけでなく本文 (`res.json()`) の受信も含む。
 * サーバの timeout 30 秒に、大きめの部分応答の転送ぶん 10 秒を足して 40 秒にする。
 * 切れたときは `requireOSMData` がキャッシュ済みの分だけで続行する。
 *
 * 仮の値。本文受信で切れると `remark` 判定ではなく時間切れ扱いになるため、
 * 部分応答のサイズ実測で見直す。
 */
export const OSM_FETCH_BUDGET_MS = 40_000;
